# Кириллические прописные, повторяющие латинские начертания.
HAND_ALIAS = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'Ё': 'E', 'К': 'K', 'М': 'M', 'Н': 'H',
    'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'У': 'Y', 'Х': 'X',
}
# Строчные кириллические рисуются прописными — см. комментарий выше.
for _up in list(range(0x410, 0x430)):
    HAND_ALIAS[chr(_up + 0x20)] = HAND_ALIAS.get(chr(_up), chr(_up))
HAND_ALIAS['ё'] = 'E'

HAND_ROWS = 8
HAND_BASELINE = 7      # базовая линия: строка 7 — подстрочная


def hand_glyph(art):
    """ASCII-арт -> матрица бит (список строк из 0/1)."""
    rows = art.split('/')
    assert len(rows) == HAND_ROWS, f"ожидалось {HAND_ROWS} строк, получено {len(rows)}"
    for r in rows:
        assert len(r) == 5, f"ожидалась ширина 5, получено {len(r)!r}"
    return [[1 if c == '#' else 0 for c in r] for r in rows]


def trim(matrix):
    """Обрезает пустые строки и столбцы. -> (bits, w, h, dx, dy_top)"""
    h, w = len(matrix), len(matrix[0]) if matrix else 0
    rows = [y for y in range(h) if any(matrix[y])]
    cols = [x for x in range(w) if any(matrix[y][x] for y in range(h))]
    if not rows or not cols:
        return [], 0, 0, 0, 0
    y0, y1 = rows[0], rows[-1]
    x0, x1 = cols[0], cols[-1]
    bits = [row[x0:x1 + 1] for row in matrix[y0:y1 + 1]]
    return bits, x1 - x0 + 1, y1 - y0 + 1, x0, y0


def build_hand_font():
    glyphs = {}
    for ch, art in HAND5x7.items():
        glyphs[ch] = hand_glyph(art)
    out = {}
    for ch, matrix in glyphs.items():
        bits, w, h, dx, ytop = trim(matrix)
        if ch == ' ':
            out[ch] = dict(bits=[], w=0, h=0, dx=0, dy=0, adv=3)
            continue
        out[ch] = dict(bits=bits, w=w, h=h, dx=dx,
                       dy=ytop - HAND_BASELINE, adv=dx + w + 1)
    for alias, src in HAND_ALIAS.items():
        if src in out:
            out[alias] = dict(out[src])
    # yAdvance равен высоте ячейки: прописные занимают строки 0..6,
    # поэтому между строками естественным образом остаётся 1 px воздуха.
    return out, HAND_ROWS, HAND_BASELINE


def build_ttf_font(path, size, charset):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    pad = size * 2
    out = {}
    for ch in charset:
        img = Image.new('L', (pad, ascent + descent + 4), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = '1'          # без сглаживания: панель одноцветная на пиксель
        d.text((2, 2), ch, font=font, fill=255)
        px = img.load()
        matrix = [[1 if px[x, y] > 127 else 0 for x in range(img.width)]
                  for y in range(img.height)]
        bits, w, h, dx, ytop = trim(matrix)
        adv = int(round(font.getlength(ch)))
        baseline = 2 + ascent
        out[ch] = dict(bits=bits, w=w, h=h, dx=dx - 2,
                       dy=ytop - baseline, adv=adv)
    return out, ascent + descent, ascent


def pack(glyphs):
    """Глифы -> (byte-массив, отсортированный список записей)."""
    blob = bytearray()
    entries = []
    for ch in sorted(glyphs, key=ord):
        g = glyphs[ch]
        off = len(blob)
        acc, nbits = 0, 0
        for row in g['bits']:
            for b in row:
                acc = (acc << 1) | b
                nbits += 1
                if nbits == 8:
                    blob.append(acc)
                    acc, nbits = 0, 0
        if nbits:
            blob.append(acc << (8 - nbits))
        entries.append((ord(ch), off, g['w'], g['h'], g['dx'], g['dy'], g['adv']))
    return bytes(blob), entries


