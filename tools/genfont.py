# Кириллические прописные, повторяющие латинские начертания.
HAND_ALIAS = {
    'А': 'A', 'В': 'B', 'Е': 'E', 'Ё': 'E', 'К': 'K', 'М': 'M', 'Н': 'H',
    'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'У': 'Y', 'Х': 'X',
}
# Строчные кириллические рисуются прописными — см. комментарий выше.
for _up in list(range(0x410, 0x430)):
    HAND_ALIAS[chr(_up + 0x20)] = HAND_ALIAS.get(chr(_up), chr(_up))
HAND_ALIAS['ё'] = 'E'

HAND_ROWS = 8
HAND_BASELINE = 7      # базовая линия: строка 7 — подстрочная


def hand_glyph(art):
    """ASCII-арт -> матрица бит (список строк из 0/1)."""
    rows = art.split('/')
    assert len(rows) == HAND_ROWS, f"ожидалось {HAND_ROWS} строк, получено {len(rows)}"
    for r in rows:
        assert len(r) == 5, f"ожидалась ширина 5, получено {len(r)!r}"
    return [[1 if c == '#' else 0 for c in r] for r in rows]


def trim(matrix):
    """Обрезает пустые строки и столбцы. -> (bits, w, h, dx, dy_top)"""
    h, w = len(matrix), len(matrix[0]) if matrix else 0
    rows = [y for y in range(h) if any(matrix[y])]
    cols = [x for x in range(w) if any(matrix[y][x] for y in range(h))]
    if not rows or not cols:
        return [], 0, 0, 0, 0
    y0, y1 = rows[0], rows[-1]
    x0, x1 = cols[0], cols[-1]
    bits = [row[x0:x1 + 1] for row in matrix[y0:y1 + 1]]
    return bits, x1 - x0 + 1, y1 - y0 + 1, x0, y0


def build_hand_font():
    glyphs = {}
    for ch, art in HAND5x7.items():
        glyphs[ch] = hand_glyph(art)
    out = {}
    for ch, matrix in glyphs.items():
        bits, w, h, dx, ytop = trim(matrix)
        if ch == ' ':
            out[ch] = dict(bits=[], w=0, h=0, dx=0, dy=0, adv=3)
            continue
        out[ch] = dict(bits=bits, w=w, h=h, dx=dx,
                       dy=ytop - HAND_BASELINE, adv=dx + w + 1)
    for alias, src in HAND_ALIAS.items():
        if src in out:
            out[alias] = dict(out[src])
    # yAdvance равен высоте ячейки: прописные занимают строки 0..6,
    # поэтому между строками естественным образом остаётся 1 px воздуха.
    return out, HAND_ROWS, HAND_BASELINE


def build_ttf_font(path, size, charset, bpp=1, line=None, icon=False):
    """bpp=1 — точка есть/нет; bpp=4 — 16 градаций, сглаживание по фону.
    line — высота строки из макета: текст стоит посередине строки, как в Figma.
    icon — шрифт значков: каждый значок по центру клетки size x size, шаг = size."""
    from PIL import Image, ImageDraw, ImageFont
    from fontTools.ttLib import TTFont
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    # Шаг буквы — из метрик шрифта без хинтинга, как в Figma. PIL округляет его по
    # буквам с хинтингом, и строка Onest 16 выходила на 5 % шире макета.
    tt = TTFont(path)
    cmap, hmtx, upm = tt.getBestCmap(), tt['hmtx'], tt['head'].unitsPerEm
    pad = size * 2
    out = {}
    for ch in charset:
        img = Image.new('L', (pad, ascent + descent + 4), 0)
        d = ImageDraw.Draw(img)
        if bpp == 1:
            d.fontmode = '1'      # без сглаживания: табло одноцветное на пиксель
        d.text((2, 2), ch, font=font, fill=255)
        px = img.load()
        if bpp == 1:
            matrix = [[1 if px[x, y] > 127 else 0 for x in range(img.width)]
                      for y in range(img.height)]
        else:
            matrix = [[(px[x, y] * 15 + 127) // 255 for x in range(img.width)]
                      for y in range(img.height)]
        bits, w, h, dx, ytop = trim(matrix)
        if ord(ch) in cmap:
            adv = int(round(hmtx[cmap[ord(ch)]][0] * size / upm))
        else:
            adv = int(round(font.getlength(ch)))
        baseline = 2 + ascent
        out[ch] = dict(bits=bits, w=w, h=h, dx=dx - 2,
                       dy=ytop - baseline, adv=adv)
    if icon:
        # Верх строки = верх клетки; базовая линия — её середина.
        base = size // 2
        for g in out.values():
            g.update(dx=(size - g['w']) // 2, dy=(size - g['h']) // 2 - base, adv=size)
        return out, size, base
    if line:
        return out, line, (line - ascent - descent) // 2 + ascent
    return out, ascent + descent, ascent


def load_kept_font(name):
    """Растр шрифта из прошлой генерации (mock-server/fonts.json) — без пересборки.
    Так старые кегли не сдвигаются ни на пиксель, а TTF для них на машине не нужен."""
    path = os.path.join(ROOT, 'mock-server/fonts.json')
    with open(path, encoding='utf-8') as fh:
        f = json.load(fh)[name]
    out = {}
    for cp, g in f['glyphs'].items():
        bits = [[int(c, 16) for c in row] for row in g['bits']]
        out[chr(int(cp))] = dict(bits=bits, w=len(bits[0]) if bits else 0, h=len(bits),
                                 dx=g['dx'], dy=g['dy'], adv=g['adv'])
    return out, f['yAdvance'], f['baseline']


def pack(glyphs, bpp=1):
    """Глифы -> (byte-массив, отсортированный список записей).
    Точки строк подряд, без выравнивания: 1 бит — MSB-first, 4 бита — старший полубайт первым."""
    blob = bytearray()
    entries = []
    for ch in sorted(glyphs, key=ord):
        g = glyphs[ch]
        off = len(blob)
        acc, nbits = 0, 0
        for row in g['bits']:
            for b in row:
                acc = (acc << bpp) | b
                nbits += bpp
                if nbits == 8:
                    blob.append(acc)
                    acc, nbits = 0, 0
        if nbits:
            blob.append(acc << (8 - nbits))
        entries.append((ord(ch), off, g['w'], g['h'], g['dx'], g['dy'], g['adv']))
    return bytes(blob), entries


