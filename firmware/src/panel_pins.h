#pragma once
// Распиновка HUB75.
//
// Это НЕ значения по умолчанию из библиотеки. Отличие одно, но важное:
// библиотека по умолчанию вешает G2 на GPIO12, а GPIO12 — вывод выбора
// напряжения флеш-памяти при старте. Если панель притянет его к высокому
// уровню в момент включения, ESP32 не загрузится: плата молчит с подключённой
// панелью и оживает без неё.
//
// Распиновка ниже обходит GPIO12 стороной. Взята из разбора проекта
// schematik.io/projects/esp32-rgb-matrix-display-wgjb и сверена на конфликты:
// все пины различны, ни один не попадает в 6..11 (флеш) и 34..39 (только вход),
// строб-выводы GPIO0 и GPIO15 не задействованы.
//
// Пин E нужен панелям с 64 строками (развёртка 1/32): 64x64, 128x64.
// Для 64x32 (1/16) он не используется — тогда ставьте -1 и не подключайте.
// GPIO21 выбран как свободный: он не строб-вывод и не занят ничем выше.
//
// Полная карта соединений: docs/led-hub75/WIRING.md — правьте оба файла вместе.
#define PIN_R1   25
#define PIN_G1   26
#define PIN_B1   27
#define PIN_R2   14
#define PIN_G2   13
#define PIN_B2   32
#define PIN_A    33
#define PIN_B     4
#define PIN_C    16
#define PIN_D    17
#define PIN_E    21
#define PIN_LAT  23
#define PIN_OE   19
#define PIN_CLK  18

// Прежняя распиновка по умолчанию из библиотеки — на случай готовой платы
// (ESP32 Trinity и подобные), разведённой под неё. Ловушка с GPIO12 там есть.
//   R1=25 G1=26 B1=27  R2=14 G2=12 B2=13
//   A=23  B=19  C=5    D=17  LAT=4 OE=15 CLK=16
